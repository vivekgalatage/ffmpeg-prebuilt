#!/usr/bin/env bash
# Fetches the minimum of Chromium needed to build //third_party/ffmpeg:
# a sparse, blob-less, depth-1 checkout of chromium/src at a release tag,
# the FFmpeg/Opus/NASM git dependencies at the revisions that tag pins,
# plus GN, Chromium's clang, the Rust toolchain and the Debian sysroot(s).
source "$(dirname "$0")/common.sh"

mkdir -p "$WORK_DIR" "$TOOLS_DIR"

log "chromium/src @ $CHROMIUM_VERSION (sparse)"
clone_src() {
  rm -rf "$SRC_DIR"
  git clone --quiet --depth 1 --filter=blob:none --no-checkout \
    --branch "$CHROMIUM_VERSION" "$1" "$SRC_DIR"
}
if [ ! -d "$SRC_DIR/.git" ]; then
  for url in "${CHROMIUM_SRC_GITS[@]}"; do
    echo "from $url"
    if retry clone_src "$url"; then
      break
    fi
    rm -rf "$SRC_DIR"
  done
  if [ ! -d "$SRC_DIR/.git" ]; then
    echo "chromium/src @ $CHROMIUM_VERSION: no remote has it" >&2
    exit 1
  fi
fi
cd "$SRC_DIR"
git sparse-checkout set --cone \
  build build_overrides buildtools testing \
  tools/clang tools/rust \
  third_party/opus \
  third_party/rust/cxx/chromium_integration
retry git checkout --quiet
echo "chromium/src $(git remote get-url origin) @ $(git rev-parse HEAD)"
git -C "$SRC_DIR" show HEAD:chrome/VERSION > "$WORK_DIR/chrome_VERSION"

log "git dependencies"
rm -f "$WORK_DIR/deps.txt.tmp"
gitlink_sha() {
  git ls-tree HEAD "$1" | awk '$2 == "commit" { print $3 }'
}
gitlink_url() {
  local name
  name=$(git config -f .gitmodules --get-regexp '\.path$' |
    awk -v p="$1" '$2 == p { sub(/^submodule\./, "", $1); sub(/\.path$/, "", $1); print $1 }')
  git config -f .gitmodules --get "submodule.$name.url"
}
for dep in "${FFMPEG_GIT_DEPS[@]}"; do
  sha=$(gitlink_sha "$dep")
  url=$(gitlink_url "$dep")
  if [ -z "$sha" ] || [ -z "$url" ]; then
    echo "could not resolve $dep (sha='$sha' url='$url')" >&2
    exit 1
  fi
  echo "$dep  $url @ $sha"
  if [ "$(git -C "$dep" rev-parse HEAD 2>/dev/null || true)" != "$sha" ]; then
    rm -rf "$dep"
    mkdir -p "$dep"
    git -C "$dep" init --quiet
    git -C "$dep" remote add origin "$url"
    retry git -C "$dep" fetch --quiet --depth 1 origin "$sha"
    git -C "$dep" checkout --quiet FETCH_HEAD
  fi
  echo "$dep $url $sha" >> "$WORK_DIR/deps.txt.tmp"
done
sort -u "$WORK_DIR/deps.txt.tmp" > "$WORK_DIR/deps.txt"
rm -f "$WORK_DIR/deps.txt.tmp"

log "gclient-generated files"
# Normally written by `gclient runhooks`; values match a plain Linux checkout.
cat > build/config/gclient_args.gni <<'EOF'
# Generated by ffmpeg-prebuilt/scripts/fetch_sources.sh
build_with_chromium = true
checkout_android = false
checkout_android_prebuilts_build_tools = false
checkout_clang_coverage_tools = false
checkout_copybara = false
checkout_fuchsia = false
checkout_glic_e2e_tests = false
checkout_ios_webkit = false
checkout_mutter = false
checkout_openxr = false
checkout_src_internal = false
checkout_src_internal_infra = false
checkout_clusterfuzz_data = false
cros_boards = ""
cros_boards_with_qemu_images = ""
generate_location_tags = false
EOF
echo "LASTCHANGE=$(git rev-parse HEAD)-refs/tags/$CHROMIUM_VERSION" > build/util/LASTCHANGE
git log -1 --format=%ct > build/util/LASTCHANGE.committime

log "GN"
gn_rev=$(python3 - <<'EOF'
import re, sys
deps = open("DEPS").read()
m = re.search(r"'gn_version':\s*'git_revision:([0-9a-f]{40})'", deps)
if not m:
    sys.exit("gn_version not found in DEPS")
print(m.group(1))
EOF
)
if [ ! -x "$GN" ]; then
  curl "${CURL_FLAGS[@]}" -o "$TOOLS_DIR/gn.zip" \
    "https://chrome-infra-packages.appspot.com/dl/gn/gn/linux-amd64/+/git_revision:$gn_rev"
  unzip -q -o "$TOOLS_DIR/gn.zip" -d "$TOOLS_DIR/gn"
  chmod +x "$GN"
fi
"$GN" --version

log "clang"
python3 tools/clang/scripts/update.py

log "rust toolchain"
python3 tools/rust/update_rust.py

log "sysroot(s)"
python3 build/linux/sysroot_scripts/install-sysroot.py --arch=amd64
if [ "$SYSROOT_ARCH" != amd64 ]; then
  python3 build/linux/sysroot_scripts/install-sysroot.py --arch="$SYSROOT_ARCH"
fi

log "minimal GN root"
# Replace the root .gn and BUILD.gn so GN only loads what FFmpeg needs.
cp "$(dirname "$0")/../gn/dot_gn" .gn
cp "$(dirname "$0")/../gn/root_BUILD.gn" BUILD.gn

log "done"
